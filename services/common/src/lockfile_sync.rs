//! A lockfile out of sync with its manifest is repaired by code, never by a
//! model.
//!
//! A pull request changed three `package.json` files and none of their
//! lockfiles. Every CI job failed at its frozen install (`npm ci`: "not in
//! sync"; `pnpm install --frozen-lockfile`: `ERR_PNPM_LOCKFILE_CONFIG_MISMATCH`),
//! and the fix was handed to a model, which read registry pages, tried to edit
//! a `package-lock.json` by hand and ended the run failed. The fix an engineer
//! makes takes no thought: run each package manager's own lockfile command
//! and commit what it writes.
//!
//! The rules here:
//!
//! - [`mismatches`] reads a CI or sandbox log for the frozen-install errors
//!   of every package manager CoderHelm writes lockfiles for. One hit means
//!   the lockfiles are regenerated by code before any model round, for any
//!   ticket.
//! - [`repair_command`] is the one sandbox command that writes every
//!   affected lockfile with its own manager. Each lockfile reports on its own
//!   line ([`repair_marks`]), so one that can't be written never hides the
//!   ones that were. A manager that fails is tried again another way: the
//!   manager's other mode, then the current LTS Node.
//! - [`lock_manager`] names a lockfile's manager; a model's write to one is
//!   refused with [`refusal`], which points to the tool that regenerates it.
//!
//! Everything here is pure; the sandbox run and the commit are the worker's
//! (`worker::passes::generators::repair_lockfiles`).

use crate::upgrade_notes::LockTool;

/// The package manager that writes `path`, when it is a lockfile.
pub fn lock_manager(path: &str) -> Option<&'static str> {
    let p = path.trim().trim_start_matches("./");
    if p.split('/').any(|s| s == "node_modules" || s == "vendor") {
        return None;
    }
    match p.rsplit('/').next().unwrap_or(p) {
        "package-lock.json" | "npm-shrinkwrap.json" => Some("npm"),
        "pnpm-lock.yaml" => Some("pnpm"),
        "yarn.lock" => Some("yarn"),
        "bun.lock" | "bun.lockb" => Some("bun"),
        "poetry.lock" => Some("poetry"),
        "uv.lock" => Some("uv"),
        "Pipfile.lock" => Some("pipenv"),
        "Cargo.lock" => Some("cargo"),
        "Gemfile.lock" => Some("bundler"),
        "go.sum" => Some("go"),
        _ => None,
    }
}

/// What a model is told when it tries to write a lockfile.
pub fn refusal(path: &str) -> String {
    let manager = lock_manager(path).unwrap_or("its package manager");
    format!(
        "Write REFUSED for {path}: it is a lockfile, written only by {manager}, never by hand \
         (a hand-edited lockfile has wrong integrity hashes and fails the install). Change the \
         manifest (package.json, pyproject.toml, Cargo.toml, ...) and call `run_codegen`: it \
         regenerates every lockfile whose manifest this branch changes with the repository's own \
         package manager and commits the result. Nothing was written."
    )
}

/// [`refusal`] for a round whose coder has no regenerate tool (a person's
/// feedback round): the lockfile is regenerated by code once the pull
/// request's checks report it out of sync.
pub fn refusal_without_tool(path: &str) -> String {
    let manager = lock_manager(path).unwrap_or("its package manager");
    format!(
        "Write REFUSED for {path}: it is a lockfile, written only by {manager}, never by hand \
         (a hand-edited lockfile has wrong integrity hashes and fails the install). Change the \
         manifest only. CoderHelm regenerates the lockfile with {manager} itself, by code, as \
         soon as the pull request's checks report it out of sync. Nothing was written."
    )
}

/// One frozen-install error a log shows.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Mismatch {
    pub manager: &'static str,
    /// The log line that says it, trimmed.
    pub line: String,
}

/// Lowercase needles that say a lockfile doesn't match its manifest, each
/// with the manager whose frozen install prints it.
const SIGNS: &[(&str, &str)] = &[
    // npm ci
    ("npm", "package.json and package-lock.json"),
    (
        "npm",
        "package-lock.json or npm-shrinkwrap.json are in sync",
    ),
    ("npm", "from lock file"),
    ("npm", "lock file's "),
    // pnpm install --frozen-lockfile
    ("pnpm", "err_pnpm_outdated_lockfile"),
    ("pnpm", "err_pnpm_lockfile_config_mismatch"),
    ("pnpm", "err_pnpm_frozen_lockfile_with_outdated_lockfile"),
    ("pnpm", "err_pnpm_lockfile_missing_dependency"),
    ("pnpm", "pnpm-lock.yaml is not up to date"),
    ("pnpm", "cannot proceed with the frozen installation"),
    // yarn (classic --frozen-lockfile, berry --immutable)
    ("yarn", "your lockfile needs to be updated"),
    ("yarn", "yn0028"),
    (
        "yarn",
        "the lockfile would have been modified by this install",
    ),
    // bun install --frozen-lockfile
    ("bun", "lockfile had changes, but lockfile is frozen"),
    // cargo --locked
    ("cargo", "needs to be updated but --locked was passed"),
    ("cargo", "cargo.lock needs to be updated"),
    // poetry / uv / pipenv
    ("poetry", "poetry.lock was last generated"),
    (
        "poetry",
        "poetry.lock is not consistent with pyproject.toml",
    ),
    ("uv", "uv.lock` needs to be updated"),
    ("pipenv", "pipfile.lock ("),
    // bundler (frozen / deployment)
    ("bundler", "deployment mode after changing"),
    ("bundler", "frozen mode after changing"),
    ("bundler", "gemfile.lock does not satisfy"),
    // go
    ("go", "updates to go.mod needed"),
    ("go", "updates to go.sum needed"),
    ("go", "missing go.sum entry"),
];

/// The needles that only count beside their manager's own error marker (they
/// are too plain on their own).
fn needs_context(needle: &str) -> Option<&'static str> {
    match needle {
        "from lock file" | "lock file's " => Some("npm"),
        "pipfile.lock (" => Some("out of date"),
        _ => None,
    }
}

/// The frozen-install errors in `log`, one per manager (its first line).
pub fn mismatches(log: &str) -> Vec<Mismatch> {
    let mut out: Vec<Mismatch> = Vec::new();
    for raw in log.lines() {
        let lower = raw.to_ascii_lowercase();
        for (manager, needle) in SIGNS {
            if !lower.contains(needle) || out.iter().any(|m| m.manager == *manager) {
                continue;
            }
            if let Some(ctx) = needs_context(needle) {
                if !lower.contains(ctx) {
                    continue;
                }
            }
            out.push(Mismatch {
                manager,
                line: clean_line(raw),
            });
        }
    }
    out
}

/// A log line without its CI timestamp and colour codes, kept short.
fn clean_line(raw: &str) -> String {
    let mut s = String::with_capacity(raw.len());
    let mut chars = raw.chars().peekable();
    while let Some(c) = chars.next() {
        if c == '\u{1b}' {
            // An ANSI sequence: skip to its final letter.
            for n in chars.by_ref() {
                if n.is_ascii_alphabetic() {
                    break;
                }
            }
        } else {
            s.push(c);
        }
    }
    let t = s.trim();
    // GitHub Actions prefixes each line with an RFC 3339 timestamp.
    let t = match t.split_once(' ') {
        Some((first, rest)) if first.len() >= 20 && first.contains('T') && first.ends_with('Z') => {
            rest.trim()
        }
        _ => t,
    };
    crate::truncate_str(t, 240).to_string()
}

/// The cause in one sentence, for the run page and the pull request: which
/// managers, and the line each printed.
pub fn cause(found: &[Mismatch]) -> Option<String> {
    if found.is_empty() {
        return None;
    }
    let parts: Vec<String> = found
        .iter()
        .map(|m| format!("{}: `{}`", m.manager, m.line.replace('`', "'")))
        .collect();
    Some(format!(
        "the lockfile{} out of sync with the manifests this pull request changes ({})",
        if found.len() == 1 { " is" } else { "s are" },
        parts.join("; ")
    ))
}

// ── The repair command ──────────────────────────────────────────────────

/// What each lockfile's line in the output starts with.
pub const MARK: &str = "CODERHELM_LOCKFILE";

fn dir_of(path: &str) -> &str {
    path.rsplit_once('/').map(|(d, _)| d).unwrap_or("")
}

/// The other ways a manager writes its lockfile, tried in order after its
/// usual command fails.
fn fallbacks(t: &LockTool, primary: &str) -> Vec<String> {
    let lts = |cmd: &str| format!("(n lts >/dev/null 2>&1; hash -r 2>/dev/null; {cmd})");
    match t.manager {
        "npm" => vec![format!("{primary} --legacy-peer-deps"), lts(primary)],
        "pnpm" => {
            let loose = "pnpm install --lockfile-only --ignore-scripts --no-frozen-lockfile";
            vec![loose.to_string(), lts(loose)]
        }
        "yarn" => {
            let other = if primary.contains("--mode=update-lockfile") {
                "yarn install --ignore-scripts --non-interactive --ignore-engines"
            } else {
                "yarn install --mode=update-lockfile"
            };
            vec![other.to_string(), lts(primary)]
        }
        "bun" => vec![lts(primary)],
        "cargo" => vec!["cargo update --workspace".to_string()],
        "poetry" => vec!["poetry lock".to_string()],
        _ => vec![],
    }
}

/// One lockfile's command with its fallbacks, run in the lockfile's folder.
pub fn resilient(t: &LockTool) -> String {
    let dir = dir_of(&t.lockfile);
    let prefix = format!("cd '{dir}' && ");
    let primary = t.command.strip_prefix(&prefix).unwrap_or(&t.command);
    let mut ways = vec![format!("({primary})")];
    ways.extend(fallbacks(t, primary));
    let chain = ways.join(" || ");
    if dir.is_empty() {
        format!("({chain})")
    } else {
        format!("(cd '{dir}' && ({chain}))")
    }
}

/// The one sandbox command that writes every lockfile in `tools`. Each
/// reports `CODERHELM_LOCKFILE <index> <exit code>`, and a failed one prints
/// the end of its output. The command itself always exits 0: the lockfiles
/// that were written come back whatever another one did.
pub fn repair_command(tools: &[LockTool]) -> String {
    let mut parts = Vec::new();
    for (i, t) in tools.iter().enumerate() {
        parts.push(format!(
            "{} > /tmp/coderhelm_lock_{i}.log 2>&1; c=$?; echo \"{MARK} {i} $c\"; \
             if [ $c -ne 0 ]; then tail -n 12 /tmp/coderhelm_lock_{i}.log; fi",
            resilient(t)
        ));
    }
    parts.push("true".to_string());
    parts.join("; ")
}

/// Each lockfile's exit code from a [`repair_command`] run, by index.
pub fn repair_marks(output: &str) -> Vec<(usize, i32)> {
    output
        .lines()
        .filter_map(|l| {
            let rest = l.trim().strip_prefix(MARK)?;
            let mut it = rest.split_whitespace();
            let i = it.next()?.parse().ok()?;
            let c = it.next()?.parse().ok()?;
            Some((i, c))
        })
        .collect()
}

/// What a failed lockfile printed last: the lines after its mark, up to the
/// next mark.
pub fn failure_tail(output: &str, index: usize) -> String {
    let head = format!("{MARK} {index} ");
    let mut lines = output.lines().skip_while(|l| !l.trim().starts_with(&head));
    lines.next();
    let tail: Vec<&str> = lines
        .take_while(|l| !l.trim().starts_with(MARK))
        .map(str::trim)
        .filter(|l| !l.is_empty())
        .collect();
    crate::truncate_str(&tail.join(" | "), 400).to_string()
}

/// The sandbox's changed files a lockfile repair commits: lockfiles only. A
/// manager that reformats a manifest on the way never churns the pull
/// request.
pub fn commits(path: &str) -> bool {
    lock_manager(path).is_some()
}

