//! A repository's agent file: what Coderhelm learned about the repository
//! (`pk = <team>`, `sk = AGENTS#REPO#<owner/repo>`, settings table), and when
//! it is written again by itself.
//!
//! The file is written from the repository's tree and the files that shape
//! it ([`label_of`]: manifests, CI workflows, the README and agent guidance,
//! the pull request template, lint, format and test config). Once written it
//! goes stale when those change, so:
//!
//! - a push to the default branch that changes one of those files, or adds a
//!   top-level folder, marks the record stale ([`mark_stale`]): the labels of
//!   what changed and the time of the last such push. A push that removed
//!   files under a known top-level folder asks the sweep to check whether
//!   the folder is gone ([`Record::dirs_to_check`]);
//! - the worker's 20 minute sweep regenerates a stale file once the last
//!   relevant push is [`DEBOUNCE_MINUTES`] old, at most once in
//!   [`MIN_HOURS_BETWEEN`] per repository (a claim per repository holds it),
//!   so a burst of merges is one regeneration;
//! - a file older than [`MAX_AGE_DAYS`] whose default branch has commits
//!   since is regenerated by the same sweep (pushes that were missed, files
//!   written before any of this), at most [`PER_TEAM_PER_TICK`] repositories
//!   per team per sweep.
//!
//! A file someone saved by hand (`edited_at`, set by the API) is never
//! replaced by an automatic regeneration: the sweep marks it out of date
//! (`out_of_date`, with the reasons) and the person decides. The dashboard
//! shows the generated file read only; people's own guidance lives in the
//! repository's instructions, which the generation reads, so it survives
//! every regeneration.
//!
//! Each write records why (`regenerated_reason`: install, manual, push or
//! age) and what changed (`regenerated_after`), so the dashboard can say
//! "Updated automatically on <date> after changes to package.json and CI".

use std::collections::{BTreeSet, HashMap};

use aws_sdk_dynamodb::types::AttributeValue;
use aws_sdk_dynamodb::Client as DynamoClient;
use chrono::{DateTime, Duration, Utc};
use serde_json::{json, Value};

use crate::settings_index::{Item, Spec};

pub const SK_PREFIX: &str = "AGENTS#REPO#";
/// `INDEX#AGENT_FILE`: every team that has an agent file.
pub const INDEX: &str = "AGENT_FILE";
/// The last relevant push must be this old before the file is regenerated.
pub const DEBOUNCE_MINUTES: i64 = 30;
/// At most one automatic regeneration per repository in this many hours.
pub const MIN_HOURS_BETWEEN: i64 = 24;
/// A file older than this is checked against its default branch.
pub const MAX_AGE_DAYS: i64 = 30;
/// Automatic regenerations started per team per sweep.
pub const PER_TEAM_PER_TICK: usize = 3;
/// Files read for one generation, and CI workflows among them.
pub const MAX_FILES_READ: usize = 24;
pub const MAX_WORKFLOWS_READ: usize = 6;

pub fn sk(repo: &str) -> String {
    format!("{SK_PREFIX}{repo}")
}

/// The claim that holds a repository's automatic regeneration for
/// [`MIN_HOURS_BETWEEN`] hours: taken by the sweep before it queues one.
pub fn sweep_claim_sk(repo: &str) -> String {
    format!("AGENTS_REGEN#{repo}")
}

/// The lease of one regeneration while it runs (a message delivered twice
/// runs once).
pub fn run_claim_sk(repo: &str) -> String {
    format!("AGENTS_REGEN_RUN#{repo}")
}

/// Why a file was written.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Reason {
    /// The repository was installed or turned on.
    Install,
    /// Someone pressed regenerate.
    Manual,
    /// Files that shape it changed on the default branch.
    Push,
    /// It was older than [`MAX_AGE_DAYS`] and the default branch moved.
    Age,
}

impl Reason {
    pub fn as_str(self) -> &'static str {
        match self {
            Reason::Install => "install",
            Reason::Manual => "manual",
            Reason::Push => "push",
            Reason::Age => "age",
        }
    }

    pub fn parse(s: &str) -> Option<Self> {
        match s {
            "install" => Some(Reason::Install),
            "manual" => Some(Reason::Manual),
            "push" => Some(Reason::Push),
            "age" => Some(Reason::Age),
            _ => None,
        }
    }

    /// Started by the sweep, not by a person.
    pub fn automatic(self) -> bool {
        matches!(self, Reason::Push | Reason::Age)
    }
}

