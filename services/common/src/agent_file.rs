    fn push(paths: &[(&str, &str)]) -> PushPaths {
        let mut p = PushPaths::default();
        for (kind, path) in paths {
            let set = match *kind {
                "added" => &mut p.added,
                "removed" => &mut p.removed,
                _ => &mut p.modified,
            };
            set.insert(path.to_string());
        }
        p
    }

