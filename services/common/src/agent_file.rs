fn file_name(path: &str) -> &str {
    path.rsplit('/').next().unwrap_or(path)
}

fn depth(path: &str) -> usize {
    path.matches('/').count()
}

/// The kind of file `path` is, when it shapes the agent file. Only the
/// places the generation reads count: the repository root, `.github/` and
/// `docs/` for guidance, CI configuration, and Cursor rules.
pub fn kind_of(path: &str) -> Option<Kind> {
    let path = path.trim_start_matches("./");
    let lower = path.to_ascii_lowercase();
    let name = file_name(&lower);
    let top = depth(&lower) == 0;
    let in_github = lower.starts_with(".github/") && depth(&lower) == 1;
    let in_docs = lower.starts_with("docs/") && depth(&lower) == 1;
    // Agent guidance files kept in a folder of their own.
    if (lower.starts_with(".claude/") && depth(&lower) == 1 && name == "claude.md")
        || lower == ".github/instructions.md"
        || (lower.starts_with(".github/instructions/") && name.ends_with(".md"))
    {
        return Some(Kind::Guidance);
    }

    // CI.
    if (lower.starts_with(".github/workflows/")
        && (name.ends_with(".yml") || name.ends_with(".yaml")))
        || lower == ".gitlab-ci.yml"
        || lower == ".circleci/config.yml"
        || lower == "azure-pipelines.yml"
        || lower == "bitbucket-pipelines.yml"
        || lower == "jenkinsfile"
        || lower.starts_with(".buildkite/")
    {
        return Some(Kind::Ci);
    }
    // The pull request template.
    if (name.starts_with("pull_request_template") && (top || in_github || in_docs))
        || lower.starts_with(".github/pull_request_template/")
    {
        return Some(Kind::PrTemplate);
    }
    // Cursor rules, and agent or review guidance.
    if lower.starts_with(".cursor/rules/") {
        return Some(Kind::Guidance);
    }
    if top || in_github || in_docs {
        let review_guide =
            name.ends_with(".md") && name.contains("review") && name.contains("guide");
        if GUIDANCE.contains(&name) || review_guide {
            return Some(Kind::Guidance);
        }
    }
    if !top {
        return None;
    }
    if name.starts_with("readme") {
        return Some(Kind::Readme);
    }
    if MANIFESTS.contains(&name) || MANIFEST_STEMS.iter().any(|s| name.starts_with(s)) {
        return Some(Kind::Manifest);
    }
    if TOOLING.contains(&name) || TOOLING_STEMS.iter().any(|s| name.starts_with(s)) {
        return Some(Kind::Tooling);
    }
    None
}

/// How a changed file is named to people ("package.json", "CI").
pub fn label_of(path: &str) -> Option<String> {
    let kind = kind_of(path)?;
    let path = path.trim_start_matches("./");
    Some(match kind {
        Kind::Ci => "CI".to_string(),
        Kind::PrTemplate => "the pull request template".to_string(),
        _ if path.to_ascii_lowercase().starts_with(".cursor/rules/") => "Cursor rules".to_string(),
        _ => file_name(path).to_string(),
    })
}

/// The top-level folder `path` is in, if it is in one.
pub fn top_dir(path: &str) -> Option<&str> {
    let path = path.trim_start_matches("./");
    path.split_once('/')
        .map(|(d, _)| d)
        .filter(|d| !d.is_empty())
}

/// Every top-level folder of a tree (from its file paths).
pub fn top_dirs<S: AsRef<str>>(paths: &[S]) -> Vec<String> {
    paths
        .iter()
        .filter_map(|p| top_dir(p.as_ref()))
        .map(String::from)
        .collect::<BTreeSet<_>>()
        .into_iter()
        .collect()
}

/// The files of a tree the generation reads, in order: guidance first, then
/// the README, manifests, CI (at most [`MAX_WORKFLOWS_READ`]), the pull
/// request template and tooling; at most [`MAX_FILES_READ`].
pub fn files_to_read<S: AsRef<str>>(paths: &[S]) -> Vec<String> {
    let mut found: Vec<(Kind, String)> = paths
        .iter()
        .map(|p| p.as_ref())
        .filter_map(|p| kind_of(p).map(|k| (k, p.to_string())))
        .collect();
    found.sort();
    let mut out = Vec::new();
    let mut workflows = 0;
    for (kind, path) in found {
        if kind == Kind::Ci {
            if workflows >= MAX_WORKFLOWS_READ {
                continue;
            }
            workflows += 1;
        }
        out.push(path);
        if out.len() >= MAX_FILES_READ {
            break;
        }
    }
    out
}

// ─── What a push changed ───────────────────────────────────────────────

/// The files a push touched, from its commits.
#[derive(Debug, Default, Clone, PartialEq, Eq)]
pub struct PushPaths {
    pub added: BTreeSet<String>,
    pub modified: BTreeSet<String>,
    pub removed: BTreeSet<String>,
}

impl PushPaths {
    pub fn from_payload(payload: &Value) -> Self {
        let mut out = PushPaths::default();
        for c in payload["commits"].as_array().into_iter().flatten() {
            for (key, set) in [
                ("added", &mut out.added),
                ("modified", &mut out.modified),
                ("removed", &mut out.removed),
            ] {
                for f in c[key].as_array().into_iter().flatten() {
                    if let Some(p) = f.as_str() {
                        set.insert(p.to_string());
                    }
                }
            }
        }
        out
    }

    fn all(&self) -> impl Iterator<Item = &String> {
        self.added.iter().chain(&self.modified).chain(&self.removed)
    }

    /// Whether the push could matter at all: it touched a file that shapes
    /// the agent file, or added or removed a file inside a folder. Only then
    /// is the record read.
    pub fn worth_reading(&self) -> bool {
        self.all().any(|p| kind_of(p).is_some())
            || self
                .added
                .iter()
                .chain(&self.removed)
                .any(|p| top_dir(p).is_some())
    }
}

/// What a push means for an agent file.
#[derive(Debug, Default, Clone, PartialEq, Eq)]
pub struct Changes {
    /// Labels of what changed ("package.json", "CI", "the new e2e folder").
    pub labels: BTreeSet<String>,
    /// Known top-level folders the push removed files from: the sweep
    /// checks whether they are gone.
    pub dirs_to_check: BTreeSet<String>,
}

impl Changes {
    pub fn is_empty(&self) -> bool {
        self.labels.is_empty() && self.dirs_to_check.is_empty()
    }
}

/// What `paths` changed, given the top-level folders the file was written
/// from (`None` for a record written before they were kept: folders are not
/// compared then).
pub fn changes(paths: &PushPaths, known_dirs: Option<&[String]>) -> Changes {
    let mut out = Changes::default();
    for p in paths.all() {
        if let Some(l) = label_of(p) {
            out.labels.insert(l);
        }
    }
    if let Some(known) = known_dirs {
        for p in &paths.added {
            if let Some(d) = top_dir(p) {
                if !known.iter().any(|k| k == d) {
                    out.labels.insert(format!("the new {d} folder"));
                }
            }
        }
        for p in &paths.removed {
            if let Some(d) = top_dir(p) {
                let still_added = paths.added.iter().any(|a| top_dir(a) == Some(d));
                if known.iter().any(|k| k == d) && !still_added {
                    out.dirs_to_check.insert(d.to_string());
                }
            }
        }
    }
    out
}

/// A label for a top-level folder the sweep found gone.
pub fn removed_dir_label(dir: &str) -> String {
    format!("removing the {dir} folder")
}

// ─── The record and when it is due ─────────────────────────────────────

/// What the sweep reads of an agent file record.
#[derive(Debug, Default, Clone, PartialEq)]
pub struct Record {
    pub repo: String,
    pub has_content: bool,
    /// When the file was last written by Coderhelm or saved by a person.
    pub updated_at: Option<DateTime<Utc>>,
    /// Saved by hand since it was last generated.
    pub edited: bool,
    /// Labels of what changed since it was generated.
    pub stale_reasons: Vec<String>,
    /// The last push that made it stale.
    pub last_push_at: Option<DateTime<Utc>>,
    /// Known top-level folders a push removed files from.
    pub dirs_to_check: Vec<String>,
    pub dirs_pushed_at: Option<DateTime<Utc>>,
    /// Already marked out of date (an edited file).
    pub out_of_date: bool,
    /// When the age backstop last found no new commits.
    pub age_checked_at: Option<DateTime<Utc>>,
}

fn time_of(item: &Item, key: &str) -> Option<DateTime<Utc>> {
    item.get(key)
        .and_then(|v| v.as_s().ok())
        .and_then(|s| DateTime::parse_from_rfc3339(s).ok())
        .map(|t| t.with_timezone(&Utc))
}

fn strings_of(item: &Item, key: &str) -> Vec<String> {
    match item.get(key) {
        Some(AttributeValue::Ss(v)) => v.clone(),
        Some(AttributeValue::L(v)) => v.iter().filter_map(|x| x.as_s().ok().cloned()).collect(),
        _ => vec![],
    }
}

impl Record {
    pub fn from_item(item: &Item) -> Option<Self> {
        let repo = item
            .get("sk")?
            .as_s()
            .ok()?
            .strip_prefix(SK_PREFIX)?
            .to_string();
        if !repo.contains('/') {
            return None;
        }
        Some(Record {
            repo,
            has_content: item
                .get("content")
                .and_then(|v| v.as_s().ok())
                .is_some_and(|c| !c.trim().is_empty()),
            updated_at: time_of(item, "updated_at"),
            edited: item.contains_key("edited_at"),
            stale_reasons: strings_of(item, "stale_reasons"),
            last_push_at: time_of(item, "last_push_at"),
            dirs_to_check: strings_of(item, "dirs_to_check"),
            dirs_pushed_at: time_of(item, "dirs_pushed_at"),
            out_of_date: item.get("out_of_date").and_then(|v| v.as_bool().ok()) == Some(&true),
            age_checked_at: time_of(item, "age_checked_at"),
        })
    }
}

/// Why the sweep would regenerate a file now.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Due {
    /// Stale from pushes, the last one at least [`DEBOUNCE_MINUTES`] old.
    Push,
    /// Older than [`MAX_AGE_DAYS`]: regenerate if the default branch has
    /// commits since it was written (the sweep asks GitHub).
    Age,
}

impl Due {
    pub fn reason(self) -> Reason {
        match self {
            Due::Push => Reason::Push,
            Due::Age => Reason::Age,
        }
    }
}

/// Whether `r` is due for an automatic regeneration at `now`. Pure.
pub fn due(r: &Record, now: DateTime<Utc>) -> Option<Due> {
    if !r.has_content {
        // Never written, or written empty: the install path owns it.
        return None;
    }
    let since_written = r.updated_at.map(|t| now - t);
    let cap_passed = since_written.is_none_or(|d| d >= Duration::hours(MIN_HOURS_BETWEEN));
    if let Some(push) = r.last_push_at.filter(|_| !r.stale_reasons.is_empty()) {
        // A stale file waits for the burst to end and for the daily cap;
        // the age backstop has nothing to add meanwhile.
        return (now - push >= Duration::minutes(DEBOUNCE_MINUTES) && cap_passed)
            .then_some(Due::Push);
    }
    let old = since_written.is_none_or(|d| d >= Duration::days(MAX_AGE_DAYS));
    let checked_lately = r
        .age_checked_at
        .is_some_and(|t| now - t < Duration::hours(MIN_HOURS_BETWEEN));
    (old && !checked_lately).then_some(Due::Age)
}

/// The order a team's due files are taken in: pushes first, then the
/// oldest file; at most `cap`.
pub fn pick(mut due: Vec<(Record, Due)>, cap: usize) -> Vec<(Record, Due)> {
    due.sort_by(|(a, da), (b, db)| {
        let rank = |d: &Due| matches!(d, Due::Age);
        rank(da)
            .cmp(&rank(db))
            .then(a.updated_at.cmp(&b.updated_at))
            .then(a.repo.cmp(&b.repo))
    });
    due.truncate(cap);
    due
}

/// The record after a push marked it stale (what [`mark_stale`] writes).
/// Pure: for tests and for reasoning about the write.
pub fn apply_push(r: &mut Record, c: &Changes, at: DateTime<Utc>) {
    if !c.labels.is_empty() {
        for l in &c.labels {
            if !r.stale_reasons.contains(l) {
                r.stale_reasons.push(l.clone());
            }
        }
        r.last_push_at = Some(at);
    }
    if !c.dirs_to_check.is_empty() {
        for d in &c.dirs_to_check {
            if !r.dirs_to_check.contains(d) {
                r.dirs_to_check.push(d.clone());
            }
        }
        r.dirs_pushed_at = Some(at);
    }
}

/// The record after a generation that started at `started` (what
/// [`store_generated`] writes): stale marks from pushes before it are
/// cleared, a push during it stays.
pub fn apply_generated(r: &mut Record, started: DateTime<Utc>, finished: DateTime<Utc>) {
    r.has_content = true;
    r.updated_at = Some(finished);
    r.edited = false;
    r.out_of_date = false;
    r.age_checked_at = None;
    if r.last_push_at.is_none_or(|p| p <= started) {
        r.stale_reasons.clear();
        r.last_push_at = None;
    }
    if r.dirs_pushed_at.is_none_or(|p| p <= started) {
        r.dirs_to_check.clear();
        r.dirs_pushed_at = None;
    }
}

// ─── Storage ───────────────────────────────────────────────────────────

fn s(v: &str) -> AttributeValue {
    AttributeValue::S(v.to_string())
}

fn ss(v: &BTreeSet<String>) -> AttributeValue {
    AttributeValue::Ss(v.iter().cloned().collect())
}

fn list(v: &[String]) -> AttributeValue {
    AttributeValue::L(v.iter().map(|x| s(x)).collect())
}

/// Marks a repository's agent file stale after a push (gateway). Only an
/// existing record is marked; a repository without a file has nothing to
/// refresh. The record is read first only when the push could matter.
pub async fn on_push(
    dynamo: &DynamoClient,
    table: &str,
    team_id: &str,
    repo: &str,
    paths: &PushPaths,
    now: DateTime<Utc>,
) -> Result<Changes, String> {
    if !paths.worth_reading() {
        return Ok(Changes::default());
    }
    let item = dynamo
        .get_item()
        .table_name(table)
        .key("pk", s(team_id))
        .key("sk", s(&sk(repo)))
        .projection_expression("pk, top_dirs")
        .send()
        .await
        .map_err(|e| format!("agent file read: {e}"))?;
    let Some(item) = item.item() else {
        return Ok(Changes::default());
    };
    let known = item
        .contains_key("top_dirs")
        .then(|| strings_of(item, "top_dirs"));
    let c = changes(paths, known.as_deref());
    if !c.is_empty() {
        mark_stale(dynamo, table, team_id, repo, &c, now).await?;
    }
    Ok(c)
}

/// The write behind [`apply_push`].
pub async fn mark_stale(
    dynamo: &DynamoClient,
    table: &str,
    team_id: &str,
    repo: &str,
    c: &Changes,
    now: DateTime<Utc>,
) -> Result<(), String> {
    let mut sets: Vec<&str> = Vec::new();
    let mut adds: Vec<&str> = Vec::new();
    let mut req = dynamo
        .update_item()
        .table_name(table)
        .key("pk", s(team_id))
        .key("sk", s(&sk(repo)))
        .condition_expression("attribute_exists(pk)")
        .expression_attribute_values(":now", s(&now.to_rfc3339()));
    if !c.labels.is_empty() {
        sets.push("last_push_at = :now");
        sets.push("stale_since = if_not_exists(stale_since, :now)");
        adds.push("stale_reasons :labels");
        req = req.expression_attribute_values(":labels", ss(&c.labels));
    }
    if !c.dirs_to_check.is_empty() {
        sets.push("dirs_pushed_at = :now");
        adds.push("dirs_to_check :dirs");
        req = req.expression_attribute_values(":dirs", ss(&c.dirs_to_check));
    }
    if sets.is_empty() {
        return Ok(());
    }
    let expr = format!("SET {} ADD {}", sets.join(", "), adds.join(", "));
    match req.update_expression(expr).send().await {
        Ok(_) => Ok(()),
        Err(e) => {
            let gone = e
                .as_service_error()
                .is_some_and(|se| se.is_conditional_check_failed_exception());
            if gone {
                Ok(())
            } else {
                Err(format!("agent file mark stale: {e}"))
            }
        }
    }
}

/// What one generation wrote.
pub struct Generated<'a> {
    pub content: &'a str,
    pub reason: Reason,
    /// What changed, for a regeneration after pushes.
    pub after: &'a [String],
    pub top_dirs: &'a [String],
    /// When the generation started reading the repository.
    pub started: DateTime<Utc>,
}

/// Writes a generated file (worker), the write behind [`apply_generated`].
/// An automatic regeneration keeps the text it replaced in
/// `previous_content`. Stale marks from pushes before `started` are cleared
/// in a second, conditional write, so a push during the generation keeps
/// the file stale.
pub async fn store_generated(
    dynamo: &DynamoClient,
    table: &str,
    team_id: &str,
    repo: &str,
    g: &Generated<'_>,
) -> Result<(), String> {
    let now = Utc::now().to_rfc3339();
    let mut set = vec![
        "content = :c",
        "updated_at = :t",
        "generated_at = :t",
        "regenerated_reason = :r",
        "regenerated_after = :after",
        "top_dirs = :dirs",
    ];
    if g.reason.automatic() {
        set.push("previous_content = if_not_exists(content, :empty)");
    }
    let expr = format!(
        "SET {} REMOVE edited_at, edited_by, out_of_date, out_of_date_reasons, age_checked_at",
        set.join(", ")
    );
    let mut req = dynamo
        .update_item()
        .table_name(table)
        .key("pk", s(team_id))
        .key("sk", s(&sk(repo)))
        .update_expression(expr)
        .expression_attribute_values(":c", s(g.content))
        .expression_attribute_values(":t", s(&now))
        .expression_attribute_values(":r", s(g.reason.as_str()))
        .expression_attribute_values(":after", list(g.after))
        .expression_attribute_values(":dirs", list(g.top_dirs));
    if g.reason.automatic() {
        req = req.expression_attribute_values(":empty", s(""));
    }
    req.send()
        .await
        .map_err(|e| format!("agent file write: {e}"))?;
    let started = g.started.to_rfc3339();
    for (attrs, at) in [
        ("stale_reasons, stale_since, last_push_at", "last_push_at"),
        ("dirs_to_check, dirs_pushed_at", "dirs_pushed_at"),
    ] {
        // Fails (and keeps the marks) only when a push came in meanwhile.
        let _ = dynamo
            .update_item()
            .table_name(table)
            .key("pk", s(team_id))
            .key("sk", s(&sk(repo)))
            .update_expression(format!("REMOVE {attrs}"))
            .condition_expression(format!("attribute_not_exists({at}) OR {at} <= :started"))
            .expression_attribute_values(":started", s(&started))
            .send()
            .await;
    }
    Ok(())
}

/// Saves a person's own text for the file (gateway): marked edited, so no
/// automatic regeneration replaces it.
pub async fn save_edit(
    dynamo: &DynamoClient,
    table: &str,
    team_id: &str,
    repo: &str,
    content: &str,
    who: &str,
) -> Result<(), String> {
    let now = Utc::now().to_rfc3339();
    dynamo
        .update_item()
        .table_name(table)
        .key("pk", s(team_id))
        .key("sk", s(&sk(repo)))
        .update_expression(
            "SET content = :c, updated_at = :t, edited_at = :t, edited_by = :w \
             REMOVE out_of_date, out_of_date_reasons",
        )
        .expression_attribute_values(":c", s(content))
        .expression_attribute_values(":t", s(&now))
        .expression_attribute_values(":w", s(who))
        .send()
        .await
        .map(|_| ())
        .map_err(|e| format!("agent file save: {e}"))
}

/// Marks an edited file out of date instead of replacing it (worker).
pub async fn mark_out_of_date(
    dynamo: &DynamoClient,
    table: &str,
    team_id: &str,
    repo: &str,
    reasons: &[String],
) -> Result<(), String> {
    dynamo
        .update_item()
        .table_name(table)
        .key("pk", s(team_id))
        .key("sk", s(&sk(repo)))
        .update_expression("SET out_of_date = :y, out_of_date_reasons = :r, out_of_date_at = :t")
        .condition_expression("attribute_exists(pk)")
        .expression_attribute_values(":y", AttributeValue::Bool(true))
        .expression_attribute_values(":r", list(reasons))
        .expression_attribute_values(":t", s(&Utc::now().to_rfc3339()))
        .send()
        .await
        .map(|_| ())
        .map_err(|e| format!("agent file out of date: {e}"))
}

/// Notes that the age backstop found no commits since the file was written,
/// so it asks GitHub again only after [`MIN_HOURS_BETWEEN`] hours.
pub async fn note_age_checked(dynamo: &DynamoClient, table: &str, team_id: &str, repo: &str) {
    let _ = dynamo
        .update_item()
        .table_name(table)
        .key("pk", s(team_id))
        .key("sk", s(&sk(repo)))
        .update_expression("SET age_checked_at = :t")
        .condition_expression("attribute_exists(pk)")
        .expression_attribute_values(":t", s(&Utc::now().to_rfc3339()))
        .send()
        .await;
}

/// After the sweep looked at the folders a push removed files from: the
/// ones that are gone make the file stale (as of that push), and the check
/// is cleared either way.
pub async fn settle_dirs(
    dynamo: &DynamoClient,
    table: &str,
    team_id: &str,
    repo: &str,
    gone: &[String],
    pushed_at: DateTime<Utc>,
) -> Result<(), String> {
    let mut req = dynamo
        .update_item()
        .table_name(table)
        .key("pk", s(team_id))
        .key("sk", s(&sk(repo)))
        .condition_expression("attribute_exists(pk)");
    let expr = if gone.is_empty() {
        "REMOVE dirs_to_check, dirs_pushed_at".to_string()
    } else {
        let labels: BTreeSet<String> = gone.iter().map(|d| removed_dir_label(d)).collect();
        req = req
            .expression_attribute_values(":labels", ss(&labels))
            .expression_attribute_values(":at", s(&pushed_at.to_rfc3339()));
        // Folders that were not gone are not checked again.
        "SET last_push_at = :at, stale_since = if_not_exists(stale_since, :at) \
         ADD stale_reasons :labels REMOVE dirs_to_check, dirs_pushed_at"
            .to_string()
    };
    req.update_expression(expr)
        .send()
        .await
        .map(|_| ())
        .map_err(|e| format!("agent file folders: {e}"))
}

/// The dashboard's view of a record: the text, when and why it was last
/// written, and whether it waits on a person.
pub fn view(item: Option<&HashMap<String, AttributeValue>>) -> Value {
    let Some(item) = item else {
        return json!({ "content": "" });
    };
    let get = |k: &str| item.get(k).and_then(|v| v.as_s().ok()).cloned();
    let out_of_date = item.get("out_of_date").and_then(|v| v.as_bool().ok()) == Some(&true);
    json!({
        "content": get("content").unwrap_or_default(),
        "updated_at": get("updated_at"),
        "generated_at": get("generated_at"),
        "regenerated_reason": get("regenerated_reason"),
        "regenerated_after": strings_of(item, "regenerated_after"),
        "edited": item.contains_key("edited_at"),
        "edited_at": get("edited_at"),
        "out_of_date": out_of_date,
        "out_of_date_reasons": strings_of(item, "out_of_date_reasons"),
        "stale_reasons": strings_of(item, "stale_reasons"),
    })
}

/// The index member a record stands for: its team.
pub fn member_of(item: &Item) -> Option<String> {
    let sk = item.get("sk")?.as_s().ok()?;
    sk.strip_prefix(SK_PREFIX).filter(|r| r.contains('/'))?;
    let pk = item.get("pk")?.as_s().ok()?;
    (!pk.is_empty() && !pk.starts_with("INDEX#")).then(|| pk.clone())
}

/// How the daily rebuild finds every team with an agent file.
pub fn index_spec() -> Spec<'static> {
    Spec {
        name: INDEX,
        filter: "begins_with(sk, :pfx)",
        values: vec![(":pfx", s(SK_PREFIX))],
        member_of,
    }
}

