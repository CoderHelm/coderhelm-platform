    #[test]
    fn five_quick_pushes_make_one_regeneration() {
        let mut r = fresh("2026-10-01T00:00:00Z");
        let c = changes(&push(&[("modified", "package.json")]), None);
        let ci = changes(&push(&[("modified", ".github/workflows/ci.yml")]), None);
        // Five merges, four minutes apart.
        for (i, ch) in [&c, &ci, &c, &ci, &c].iter().enumerate() {
            let at = t("2026-11-02T10:00:00Z") + Duration::minutes(4 * i as i64);
            apply_push(&mut r, ch, at);
        }
        assert_eq!(
            r.stale_reasons,
            vec!["package.json".to_string(), "CI".to_string()]
        );
        // The 20 minute tick, for a day.
        let mut regenerations = vec![];
        let mut now = t("2026-11-02T10:00:00Z");
        for _ in 0..72 {
            if due(&r, now) == Some(Due::Push) {
                regenerations.push(now);
                apply_generated(&mut r, now, now + Duration::minutes(1));
            }
            now += Duration::minutes(20);
        }
        assert_eq!(regenerations.len(), 1, "{regenerations:?}");
        // Not before the last push is 30 minutes old (10:16 + 30 = 10:46).
        assert_eq!(regenerations[0], t("2026-11-02T11:00:00Z"));
        assert!(r.stale_reasons.is_empty());
    }

