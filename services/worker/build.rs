//! The version of the code that checks a change, for `passes::checks_version`.
//!
//! A hold CoderHelm's own checks write into a pull request's description is
//! text: nothing ran the check again when the code that wrote it changed, so
//! a pull request held by a rule that was later fixed stayed held. Each such
//! line now carries the version of the code that wrote it, and the ready
//! sweep checks the pull request again when the running code differs.
//!
//! The version is a hash of the worker's and the common crate's sources, so
//! it is the same wherever the same code runs (hosted or a self-hosted
//! install) and changes whenever that code does, with no build step to
//! remember.

//!
//! It also lists the incident regression cases
//! (`src/passes/incidents/*.rs`) into `$OUT_DIR/incidents.rs`, which
//! `passes/incidents/mod.rs` includes: a new case is a new file and nothing
//! else, so two pull requests that each add one never edit the same line.

use std::path::{Path, PathBuf};

/// The incident cases: every `<name>.rs` in the incidents folder except
/// `mod.rs` and the shared `fixture.rs`, by name.
fn incident_cases(dir: &Path) -> Vec<String> {
    let mut names: Vec<String> = std::fs::read_dir(dir)
        .into_iter()
        .flatten()
        .flatten()
        .filter_map(|e| {
            let name = e.file_name().to_string_lossy().to_string();
            let stem = name.strip_suffix(".rs")?.to_string();
            let ident = !stem.is_empty()
                && stem
                    .chars()
                    .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
                && stem.starts_with(|c: char| c.is_ascii_lowercase());
            (ident && stem != "mod" && stem != "fixture").then_some(stem)
        })
        .collect();
    names.sort();
    names
}

/// Writes the `mod` line of each incident case, and their names, for
/// `passes/incidents/mod.rs` to include.
fn write_incidents(root: &Path) {
    let dir = root.join("src/passes/incidents");
    println!("cargo:rerun-if-changed={}", dir.display());
    let cases = incident_cases(&dir);
    let mut out = String::from("// Generated by worker/build.rs from src/passes/incidents/*.rs.\n");
    for c in &cases {
        let file = dir.join(format!("{c}.rs"));
        out.push_str(&format!(
            "#[path = {:?}]\nmod {c};\n",
            file.to_string_lossy()
        ));
    }
    out.push_str(&format!(
        "/// Every case compiled into the suite, by name.\npub(super) const CASES: &[&str] = &{cases:?};\n"
    ));
    let target = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR")).join("incidents.rs");
    if std::fs::read_to_string(&target).ok().as_deref() != Some(out.as_str()) {
        std::fs::write(&target, out).expect("write incidents.rs");
    }
}

/// Lists every file of the vendored Floorplan release (`vendor/floorplan`)
/// into `$OUT_DIR/floorplan_files.rs` as `(path, bytes)` pairs, for
/// `passes::app_map` to send to the sandbox. The files are included as they
/// are: nothing in the vendored folder is edited. CoderHelm's own detectors
/// (`floorplan/coderhelm`) go beside them as `CODERHELM_FILES`.
fn write_floorplan(root: &Path) {
    let dir = root.join("../../vendor/floorplan");
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut all = Vec::new();
    files(&dir, &mut all);
    all.sort();
    let mut out = String::from("// Generated by worker/build.rs from vendor/floorplan.\npub(crate) const FLOORPLAN_FILES: &[(&str, &[u8])] = &[\n");
    for p in &all {
        let rel = p
            .strip_prefix(&dir)
            .unwrap_or(p)
            .to_string_lossy()
            .replace('\\', "/");
        let abs = p.canonicalize().unwrap_or_else(|_| p.clone());
        out.push_str(&format!(
            "    ({rel:?}, include_bytes!({:?})),\n",
            abs.to_string_lossy()
        ));
    }
    out.push_str("];\n");
    // CoderHelm's own detectors, run by the driver after Floorplan's build
    let ours = root.join("floorplan/coderhelm");
    println!("cargo:rerun-if-changed={}", ours.display());
    let mut mine = Vec::new();
    files(&ours, &mut mine);
    mine.sort();
    out.push_str("/// CoderHelm's detectors (services/worker/floorplan/coderhelm), as `(path, bytes)`.\npub(crate) const CODERHELM_FILES: &[(&str, &[u8])] = &[\n");
    for p in &mine {
        let rel = p
            .strip_prefix(&ours)
            .unwrap_or(p)
            .to_string_lossy()
            .replace('\\', "/");
        let abs = p.canonicalize().unwrap_or_else(|_| p.clone());
        out.push_str(&format!(
            "    ({rel:?}, include_bytes!({:?})),\n",
            abs.to_string_lossy()
        ));
    }
    out.push_str("];\n");
    let target =
        PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR")).join("floorplan_files.rs");
    if std::fs::read_to_string(&target).ok().as_deref() != Some(out.as_str()) {
        std::fs::write(&target, out).expect("write floorplan_files.rs");
    }
}

fn files(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return;
    };
    for e in entries.flatten() {
        let p = e.path();
        if p.is_dir() {
            files(&p, out);
        } else {
            out.push(p);
        }
    }
}

/// FNV-1a, 64 bits: stable across toolchains, unlike the standard hasher.
fn fnv(hash: &mut u64, bytes: &[u8]) {
    for b in bytes {
        *hash ^= u64::from(*b);
        *hash = hash.wrapping_mul(0x0100_0000_01b3);
    }
}

fn main() {
    let root = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap_or_else(|_| ".".into()));
    let dirs = [root.join("src"), root.join("../common/src")];
    let mut all = Vec::new();
    for d in &dirs {
        println!("cargo:rerun-if-changed={}", d.display());
        files(d, &mut all);
    }
    // The same order everywhere: by path relative to the crate.
    let mut named: Vec<(String, PathBuf)> = all
        .into_iter()
        .map(|p| {
            let rel = p
                .strip_prefix(&root)
                .unwrap_or(&p)
                .to_string_lossy()
                .replace('\\', "/");
            (rel, p)
        })
        .collect();
    named.sort();
    let mut hash: u64 = 0xcbf2_9ce4_8422_2325;
    for (rel, p) in &named {
        fnv(&mut hash, rel.as_bytes());
        fnv(&mut hash, &[0]);
        if let Ok(bytes) = std::fs::read(p) {
            fnv(&mut hash, &bytes);
        }
        fnv(&mut hash, &[0]);
    }
    println!("cargo:rustc-env=CODERHELM_CHECKS_VERSION={hash:016x}");
    write_incidents(&root);
    write_floorplan(&root);
}
